-- =============================================================================
-- V4 — NEVOLYN Office & R&D Management Schema
-- Consolidates users, attendance, rnd_projects, tasks, experiments,
-- development_records, work_logs, trainings_meetings, uploaded_files, audit_logs
-- =============================================================================

-- 1. users
CREATE TABLE IF NOT EXISTS users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id         VARCHAR(50)     NOT NULL UNIQUE,
    username            VARCHAR(100)    NOT NULL UNIQUE,
    password_hash       TEXT            NOT NULL,
    full_name           VARCHAR(255)    NOT NULL,
    designation         VARCHAR(255),
    joining_date        DATE,
    phone               VARCHAR(30),
    email               VARCHAR(255),
    bank_name           VARCHAR(255),
    bank_account_name   VARCHAR(255),
    bank_account_number VARCHAR(100),
    bank_branch         VARCHAR(255),
    bank_routing_number VARCHAR(100),
    role                VARCHAR(50)     NOT NULL DEFAULT 'employee',
    is_active           BOOLEAN         NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_username    ON users(username);
CREATE INDEX IF NOT EXISTS idx_users_employee_id ON users(employee_id);
CREATE INDEX IF NOT EXISTS idx_users_role        ON users(role);
CREATE INDEX IF NOT EXISTS idx_users_is_active   ON users(is_active);

-- 2. attendance
CREATE TABLE IF NOT EXISTS attendance (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT          NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    date            DATE            NOT NULL,
    check_in_time   TIME,
    check_out_time  TIME,
    total_hours     NUMERIC(5, 2)   NOT NULL DEFAULT 0.00,
    late_status     VARCHAR(50)     NOT NULL DEFAULT 'On Time',
    early_checkout  VARCHAR(50)     NOT NULL DEFAULT 'No',
    status          VARCHAR(50)     NOT NULL DEFAULT 'Present',
    ip_address      VARCHAR(45),
    user_agent      TEXT,
    notes           TEXT,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_attendance_user_date UNIQUE (user_id, date)
);

CREATE INDEX IF NOT EXISTS idx_attendance_user_id ON attendance(user_id);
CREATE INDEX IF NOT EXISTS idx_attendance_date    ON attendance(date);
CREATE INDEX IF NOT EXISTS idx_attendance_status  ON attendance(status);

-- 3. rnd_projects
CREATE TABLE IF NOT EXISTS rnd_projects (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)     NOT NULL UNIQUE,
    name            VARCHAR(255)    NOT NULL,
    objective       TEXT,
    description     TEXT,
    responsible_id  BIGINT          REFERENCES users(id) ON DELETE SET NULL,
    start_date      DATE,
    target_date     DATE,
    status          VARCHAR(50)     NOT NULL DEFAULT 'Pending',
    progress_pct    INTEGER         NOT NULL DEFAULT 0,
    remarks         TEXT,
    created_by      BIGINT          NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rnd_projects_status ON rnd_projects(status);
CREATE INDEX IF NOT EXISTS idx_rnd_projects_code   ON rnd_projects(code);

-- 4. tasks
CREATE TABLE IF NOT EXISTS tasks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT          REFERENCES rnd_projects(id) ON DELETE SET NULL,
    title           VARCHAR(500)    NOT NULL,
    description     TEXT,
    assigned_to_id  BIGINT          NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    start_date      DATE,
    deadline        DATE,
    priority        VARCHAR(50)     NOT NULL DEFAULT 'Medium',
    status          VARCHAR(50)     NOT NULL DEFAULT 'Pending',
    progress_pct    INTEGER         NOT NULL DEFAULT 0,
    remarks         TEXT,
    created_by      BIGINT          NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tasks_assigned_to_id ON tasks(assigned_to_id);
CREATE INDEX IF NOT EXISTS idx_tasks_project_id     ON tasks(project_id);
CREATE INDEX IF NOT EXISTS idx_tasks_status         ON tasks(status);
CREATE INDEX IF NOT EXISTS idx_tasks_priority       ON tasks(priority);
CREATE INDEX IF NOT EXISTS idx_tasks_deadline       ON tasks(deadline);

-- 5. experiments
CREATE TABLE IF NOT EXISTS experiments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT          NOT NULL REFERENCES rnd_projects(id) ON DELETE CASCADE,
    title           VARCHAR(500)    NOT NULL,
    experiment_date DATE            NOT NULL,
    researcher_id   BIGINT          NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    objective       TEXT,
    procedure       TEXT,
    result          TEXT,
    observation     TEXT,
    conclusion      TEXT,
    remarks         TEXT,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_experiments_project_id    ON experiments(project_id);
CREATE INDEX IF NOT EXISTS idx_experiments_researcher_id ON experiments(researcher_id);
CREATE INDEX IF NOT EXISTS idx_experiments_date          ON experiments(experiment_date);

-- 6. development_records
CREATE TABLE IF NOT EXISTS development_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT          NOT NULL REFERENCES rnd_projects(id) ON DELETE CASCADE,
    product_name    VARCHAR(255)    NOT NULL,
    stage           VARCHAR(100)    NOT NULL,
    version         VARCHAR(50),
    record_date     DATE            NOT NULL,
    responsible_id  BIGINT          NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    result          TEXT,
    issues          TEXT,
    next_action     TEXT,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_development_records_project_id     ON development_records(project_id);
CREATE INDEX IF NOT EXISTS idx_development_records_responsible_id ON development_records(responsible_id);
CREATE INDEX IF NOT EXISTS idx_development_records_record_date    ON development_records(record_date);

-- 7. work_logs
CREATE TABLE IF NOT EXISTS work_logs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT          NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    log_date          DATE            NOT NULL,
    work_completed    TEXT            NOT NULL,
    time_spent_hours  NUMERIC(4, 2)   NOT NULL DEFAULT 0.00,
    issues            TEXT,
    next_action       TEXT,
    remarks           TEXT,
    submitted_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_work_logs_user_date UNIQUE (user_id, log_date)
);

CREATE INDEX IF NOT EXISTS idx_work_logs_user_id  ON work_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_work_logs_log_date ON work_logs(log_date);

-- 8. trainings_meetings
CREATE TABLE IF NOT EXISTS trainings_meetings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(500)    NOT NULL,
    session_type        VARCHAR(50)     NOT NULL DEFAULT 'Training',
    session_date        DATE            NOT NULL,
    trainer_presenter   VARCHAR(255),
    participants        TEXT,
    duration_minutes    INTEGER         NOT NULL DEFAULT 60,
    notes               TEXT,
    outcome             TEXT,
    remarks             TEXT,
    created_by          BIGINT          NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_trainings_meetings_session_date ON trainings_meetings(session_date);
CREATE INDEX IF NOT EXISTS idx_trainings_meetings_type         ON trainings_meetings(session_type);
CREATE INDEX IF NOT EXISTS idx_trainings_meetings_created_by   ON trainings_meetings(created_by);

-- 9. uploaded_files
CREATE TABLE IF NOT EXISTS uploaded_files (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type       VARCHAR(50)         NOT NULL,
    entity_id         BIGINT              NOT NULL,
    original_filename VARCHAR(500)        NOT NULL,
    stored_filename   VARCHAR(500)        NOT NULL,
    file_path         TEXT                NOT NULL,
    file_size         BIGINT              NOT NULL,
    mime_type         VARCHAR(200),
    uploaded_by       BIGINT              NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    uploaded_at       TIMESTAMP           NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_uploaded_files_entity   ON uploaded_files(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_uploaded_files_uploader ON uploaded_files(uploaded_by);

-- 10. audit_logs
CREATE TABLE IF NOT EXISTS audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT          REFERENCES users(id) ON DELETE SET NULL,
    username        VARCHAR(100),
    action          VARCHAR(100)    NOT NULL,
    details         TEXT,
    ip_address      VARCHAR(45),
    target_entity   VARCHAR(100),
    target_id       BIGINT,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_user_id    ON audit_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action     ON audit_logs(action);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_target     ON audit_logs(target_entity, target_id);

